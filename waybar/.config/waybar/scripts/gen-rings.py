#!/usr/bin/env python3
"""Generate the CPU/RAM usage rings drawn behind the icons in the bar.

One SVG per 5% step per module, written to ../rings/, plus rings/rings.css
(imported by style.css) that maps the p0..p100 state classes set on
cpu#ring / memory#ring in config.jsonc to the matching SVG. Colours
match style.css (cyan / magenta, yellow at warning, red at critical).
Re-run after changing colours or thresholds: ./gen-rings.py
"""
from math import pi
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "rings"
SIZE, STROKE = 24, 2.2
R = (SIZE - STROKE) / 2
CIRC = 2 * pi * R
TRACK = "rgba(255,255,255,0.15)"

MODULES = {
    # name: (base colour, warning threshold, critical threshold)
    "cpu": ("#33ccff", 70, 90),
    "memory": ("#c162de", 75, 90),
}


def ring(pct, color):
    dash = CIRC * pct / 100
    c = SIZE / 2
    return f"""<svg xmlns="http://www.w3.org/2000/svg" width="{SIZE}" height="{SIZE}" viewBox="0 0 {SIZE} {SIZE}">
<circle cx="{c}" cy="{c}" r="{R:.2f}" fill="none" stroke="{TRACK}" stroke-width="{STROKE}"/>
<circle cx="{c}" cy="{c}" r="{R:.2f}" fill="none" stroke="{color}" stroke-width="{STROKE}" stroke-linecap="round" stroke-dasharray="{dash:.2f} {CIRC:.2f}" transform="rotate(-90 {c} {c})"{' opacity="0"' if pct == 0 else ''}/>
</svg>
"""


OUT.mkdir(exist_ok=True)
css = ["/* Generated by scripts/gen-rings.py, do not edit. */"]
for name, (base, warn, crit) in MODULES.items():
    for pct in range(0, 101, 5):
        color = "#f71118" if pct >= crit else "#ecb90f" if pct >= warn else base
        (OUT / f"{name}-{pct}.svg").write_text(ring(pct, color))
        css.append(f'#{name}.ring.p{pct} {{ background-image: url("{name}-{pct}.svg"); }}')
(OUT / "rings.css").write_text("\n".join(css) + "\n")
