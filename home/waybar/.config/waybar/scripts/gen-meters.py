#!/usr/bin/env python3
"""Generate meters.css: the thin usage line under "cpu" and "ram" in the bar.

Each module carries one p0..p100 state class (config.jsonc). For every 5%
step this writes a rule that draws a 2px track under the text and fills it
to that width. GTK colour names follow the theme imported by style.css:
accent for CPU, accent2 for memory, yellow at warning, red at critical.
Re-run after changing thresholds or meter styling: ./gen-meters.py
"""
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "meters.css"
TRACK = "@track"
WARN, CRIT = "@yellow", "@red"

MODULES = {
    # name: (base colour, warning threshold, critical threshold)
    "cpu": ("@accent", 70, 90),
    "memory": ("@accent2", 75, 90),
}

css = ["/* Generated by scripts/gen-meters.py, do not edit. */"]
for name, (base, warn, crit) in MODULES.items():
    for pct in range(0, 101, 5):
        color = CRIT if pct >= crit else WARN if pct >= warn else base
        width = max(pct, 4)  # a sliver stays visible when idle
        css.append(
            f"#{name}.p{pct} {{ background-image: "
            f"linear-gradient({color}, {color}), linear-gradient({TRACK}, {TRACK}); "
            f"background-size: {width}% 2px, 100% 2px; }}"
        )
OUT.write_text("\n".join(css) + "\n")
